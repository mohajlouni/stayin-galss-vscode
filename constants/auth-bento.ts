/** يضيف قناة شفافية سداسية إلى لون hex قبل استخدامه لحدود/خلفيات شبه شفافة. */
export function bentoAlpha(color: string, alpha: string) {
  return /^#[0-9A-Fa-f]{6}$/.test(color) ? `${color}${alpha}` : color;
}